import type { IconRegistry } from '../types';

/** Renders the generated svg-registry.ts file content from a compiled registry. */
export function renderRegistryFile(registry: IconRegistry): string {
  const names = Object.keys(registry).sort();
  const nameUnion = names.length > 0 ? names.map((name) => `'${name}'`).join(' | ') : 'never';

  return `// This file is generated by \`svg-kit generate\`. Do not edit by hand.
import type { IconRegistry } from 'expo-svg-kit';

export type IconName = ${nameUnion};

export const registry: IconRegistry = ${JSON.stringify(registry, null, 2)};

export default registry;
`;
}
