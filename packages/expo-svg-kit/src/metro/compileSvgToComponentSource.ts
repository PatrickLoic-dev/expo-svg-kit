import { parseSync } from 'svgson';
import { optimize } from 'svgo';
import { fileNameToIconName } from '../cli/kebabCase';
import { sanitizeSvgTree } from '../cli/sanitize';
import { DEFAULT_SVGO_CONFIG } from '../cli/svgoConfig';
import { svgTreeToIconDefinition } from '../cli/svgToTree';
import type { IconDefinition } from '../types';

/**
 * Compiles a single raw SVG file into the source of a standalone React component module, for
 * the Metro transformer (`import Logo from './logo.svg'`). Reuses the exact same SVGO config,
 * sanitization, and `currentColor` theming as `svg-kit generate` so a single SVG behaves the
 * same way whether it goes through the registry or is imported directly.
 */
export function compileSvgToComponentSource(rawSvg: string, fileName: string): string {
  const { multicolor } = fileNameToIconName(fileName);
  const optimized = optimize(rawSvg, { ...DEFAULT_SVGO_CONFIG, path: fileName }).data;
  const parsed = parseSync(optimized);
  const sanitized = sanitizeSvgTree(parsed);
  const definition = svgTreeToIconDefinition(sanitized, multicolor);
  return renderComponentSource(definition);
}

function renderComponentSource(definition: IconDefinition): string {
  return `// Generated by expo-svg-kit's Metro transformer. Do not edit by hand.
import * as React from 'react';
import { Svg } from 'react-native-svg';
import { renderSvgTree } from 'expo-svg-kit';

const definition = ${JSON.stringify(definition)};

export default function SvgComponent(props) {
  const { size = 24, width, height, color, colors, ...rest } = props;
  return (
    <Svg
      width={width ?? size}
      height={height ?? size}
      viewBox={definition.viewBox}
      color={color}
      {...rest}
    >
      {renderSvgTree(definition.tree, colors)}
    </Svg>
  );
}
`;
}
